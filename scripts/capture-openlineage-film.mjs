#!/usr/bin/env node
// Collect actual Relate-backed browser states. No mocked /api responses.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const root=path.resolve(process.argv[2] || 'demo/film-working');
const screens=path.join(root,'screens');
const base=process.env.DEMO_URL || 'http://127.0.0.1:8765';
await mkdir(screens,{recursive:true});
const get=async p=>{const response=await fetch(base+p);assert.equal(response.status,200,p);return response.json();};
const graph=await get('/api/graph');
const health=await get('/api/health');
assert.equal(graph.source,'openlineage');
assert.equal(health.ok,true);
const find=(name,kind='Column',dataset=null)=>{
  const hits=graph.assets.filter(a=>a.name===name&&a.kind===kind&&(!dataset||a.detail.includes(' / '+dataset+' #')));
  assert(hits.length===1,'Expected a unique '+name+' ('+kind+'), found '+hits.length);
  return hits[0];
};
const moisture=find('moisture_pct'),fieldId=find('field_id','Column','raw_harvests');
const impact=await get('/api/impact?id='+encodeURIComponent(moisture.id));
const payout=find('payout_eur'),carbon=find('co2e_per_dry_tonne');
const ids=new Set(impact.affected.map(a=>a.id));
assert(ids.has(carbon.id) && ids.has(payout.id),'Real Relate impact must reach finance and climate');
const negative=await get('/api/impact?id='+encodeURIComponent(fieldId.id));
const negativeIDs=new Set(negative.affected.map(a=>a.id));
assert(!negativeIDs.has(carbon.id)&&!negativeIDs.has(payout.id),
 'field_id falsely appears to affect payouts or carbon');
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({
 viewport:{width:1600,height:1000},deviceScaleFactor:1.5,
 colorScheme:'dark',reducedMotion:'reduce',acceptDownloads:true
});
const page=await context.newPage();
let errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('response',response=>{if(response.url().includes('/api/')&&response.status()>=400)
  errors.push('HTTP '+response.status()+': '+response.url());});
const shot=async(name,selector,options={})=>{
 const loc=page.locator(selector);
 await loc.waitFor({state:'visible',timeout:15000});
 await loc.screenshot({path:path.join(screens,name+'.png'),
   animations:'disabled',...options});
};
try{
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#focus-title')?.textContent!=='Loading relationships...');
 await shot('hero','.headline');
 await page.locator('#search').fill('moisture_pct');
 await page.locator('#suggestions .suggestion').filter({hasText:'moisture_pct'}).first().click();
 await page.waitForFunction(()=>document.querySelector('#focus-title')?.textContent==='moisture_pct');
 await page.locator('#view-network').click();
 await shot('overview-map','.work-card');
 await page.locator('#view-route').click();
 let button=page.locator('#outputs .output').filter({hasText:'co2e_per_dry_tonne'});
 assert.equal(await button.count(),1);
 await button.click();
 await shot('climate-route','.work-card');
 await shot('climate-evidence','.path-panel');
 button=page.locator('#outputs .output').filter({hasText:'payout_eur'});
 assert.equal(await button.count(),1);
 await button.click();
 await shot('finance-route','.work-card');
 await shot('finance-evidence','.path-panel');
 await shot('results','.metrics');
 // Use the actual download handler and verify receipt was generated by Relate.
 await page.locator('#change-note').fill('moisture_pct changes from percentage 0-100 to fraction 0-1');
 const saved=page.waitForEvent('download',{timeout:12000});
 await page.locator('#download-report').click();
 const download=await saved;
 await download.saveAs(path.join(root,'real-impact-receipt.md'));
 const receipt=await readFile(path.join(root,'real-impact-receipt.md'),'utf8');
 assert(receipt.includes('co2e_per_dry_tonne')&&receipt.includes('payout_eur'));
 assert(receipt.includes('Relate path'));
 await page.locator('#search').fill('field_id');
 await page.locator('#suggestions .suggestion[data-id="'+fieldId.id+'"]').click();
 await page.waitForFunction((id)=>document.querySelector('#focus-subtitle')?.textContent?.includes(id),fieldId.id);
 await shot('negative-route','.work-card');
 await shot('negative-evidence','.path-panel');
 assert.deepEqual(errors,[]);
 const metadata={
  origin:'Playwright screenshots of the real local app, live Relate API',
  synthetic_data:true,server:base,health,
  captured: ['hero','overview-map','climate-route','climate-evidence','finance-route',
             'finance-evidence','results','negative-route','negative-evidence'],
  source:moisture,target_finance:payout,target_climate:carbon,
  unrelated_field:fieldId,impact_count:impact.affected_count,
  climate_path:impact.affected.find(a=>a.id===carbon.id).paths[0].ids,
  finance_path:impact.affected.find(a=>a.id===payout.id).paths[0].ids,
  negative_targets:negative.affected.map(a=>a.name),
  errors
 };
 await writeFile(path.join(root,'capture-manifest.json'),JSON.stringify(metadata,null,2));
 console.log('OPENLINEAGE_REAL_BROWSER_VERIFIED '+JSON.stringify({
   screens:metadata.captured.length,impact:impact.affected_count,
   finance:true,climate:true,negative:true,errors:errors.length
 }));
}finally{
 await browser.close();
}
